import argparse
import csv
import os

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
CSV = os.path.join(HERE, "datasets", "MC.csv")

T_TRAIN, T_VAL, T_TEST = 5000, 1000, 1000
AMPLITUDE = 0.8
MAX_DELAY = 200                                  # delays 1..200 (values discarded at the start)
SEED = 0                                         # seed of the experiments (generator: SEED + 9999)
SPLITS = ("train", "validation", "test")


def generate(seed=SEED):
    """(U_train, U_val, U_test), arrays (T, 1): the call of the code of the paper."""
    # DeepESN Python Library (https://github.com/lucapedrelli/DeepESN). Please cite:
    #   C. Gallicchio, A. Micheli, L. Pedrelli, "Deep Reservoir Computing: A Critical
    #   Experimental Analysis", Neurocomputing, 2017, vol. 268, pp. 87-99.
    from deepesn.tasks import MemoryCapacity
    U_train, U_val, U_test = MemoryCapacity.random_input(
        T_TRAIN, T_VAL, T_TEST, amplitude=AMPLITUDE, seed=seed + 9999, skip=MAX_DELAY)
    return (np.asarray(U_train, dtype=np.float64), np.asarray(U_val, dtype=np.float64),
            np.asarray(U_test, dtype=np.float64))


def save(parts, path=CSV):
    os.makedirs(os.path.dirname(os.path.abspath(path)), exist_ok=True)
    with open(path, "w", newline="") as f:
        w = csv.writer(f)
        w.writerow(["t", "split", "u"])
        t = 0
        for name, x in zip(SPLITS, parts):
            for v in x[:, 0]:
                w.writerow([t, name, repr(float(v))])
                t += 1


def load(path=CSV):
    """(U_train, U_val, U_test) of the CSV, arrays (T, 1)."""
    seg = {s: [] for s in SPLITS}
    with open(path, newline="") as f:
        for row in csv.DictReader(f):
            seg[row["split"]].append(float(row["u"]))
    return tuple(np.array(seg[s], dtype=np.float64)[:, None] for s in SPLITS)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--csv", default=CSV)
    a = ap.parse_args()
    parts = generate()
    save(parts, a.csv)
    same = all(np.array_equal(x, y) for x, y in zip(load(a.csv), parts))
    print(f"{a.csv}: {T_TRAIN} + {T_VAL} + {T_TEST} steps; read back identical bit by bit: {same}")
    if not same:
        raise SystemExit(1)


if __name__ == "__main__":
    main()
